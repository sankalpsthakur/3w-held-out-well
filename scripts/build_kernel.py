"""Build a self-contained Kaggle script kernel: base64(zip(src/w3, protocol files, entry script)) + bootstrap.

usage: python scripts/build_kernel.py <kernel-slug> <entry-script> [--files path ...] [--internet true|false]
Writes kaggle/<slug>/main.py and kernel-metadata.json (private, CPU only). Push with `kaggle kernels push -p kaggle/<slug>`.
"""
import argparse
import base64
import hashlib
import io
import json
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
USER = "sankalpsthakur"

ap = argparse.ArgumentParser()
ap.add_argument("slug")
ap.add_argument("entry")
ap.add_argument("--files", nargs="*", default=[])
ap.add_argument("--internet", default="true")
ap.add_argument("--config", default="{}", help="JSON written to data/config.json inside the payload")
a = ap.parse_args()

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    for p in sorted((ROOT / "src" / "w3").glob("*.py")):
        z.write(p, f"w3/{p.name}")
    for rel in a.files:
        z.write(ROOT / rel, f"data/{Path(rel).name}")
    z.writestr("data/config.json", a.config)
    z.write(ROOT / a.entry, "entry.py")
raw = buf.getvalue()
sha = hashlib.sha256(raw).hexdigest()
b64 = base64.b64encode(raw).decode()
boot = f'''# generated by scripts/build_kernel.py -- do not edit. payload sha256 {sha}
import base64, hashlib, io, os, runpy, sys, zipfile
PAYLOAD_SHA256 = "{sha}"
PAYLOAD = "{b64}"
raw = base64.b64decode(PAYLOAD)
assert hashlib.sha256(raw).hexdigest() == PAYLOAD_SHA256, "payload corrupted"
os.makedirs("/tmp/w3code", exist_ok=True)
zipfile.ZipFile(io.BytesIO(raw)).extractall("/tmp/w3code")
sys.path.insert(0, "/tmp/w3code")
print("payload sha256", PAYLOAD_SHA256, flush=True)
runpy.run_path("/tmp/w3code/entry.py", run_name="__main__")
'''
out = ROOT / "kaggle" / a.slug
out.mkdir(parents=True, exist_ok=True)
(out / "main.py").write_text(boot)
meta = {"id": f"{USER}/{a.slug}", "title": a.slug, "code_file": "main.py", "language": "python", "kernel_type": "script",
        "is_private": "true", "enable_gpu": "false", "enable_tpu": "false", "enable_internet": a.internet,
        "machine_shape": "", "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}
assert a.slug.startswith("bench-events-")
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
print(f"{out}/main.py  {len(boot)/1e3:.0f} kB  payload sha256 {sha}")
